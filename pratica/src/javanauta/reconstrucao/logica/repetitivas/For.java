package reconstrucao.logica.repetitivas;

public class For {
    public static void main(String[] args) {

        //Reconstrução Javanauta - For

        //--> Reconstrução com For (bem simples)
        for (int cont = 1; cont < 10; cont++) {
            System.out.println("Repetição número " + cont + "!");
        }
    }
}
